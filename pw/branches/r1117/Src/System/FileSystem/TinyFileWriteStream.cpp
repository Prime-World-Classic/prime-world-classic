TinyFileWriteStream::TinyFileWriteStream( const string & fileName, int flags /*= BINARY*/ )
  : hFile(0)
{
  const char *mode;
  
  if( flags & BINARY )
    mode = "wb";
  else
    mode = "w";

  hFile = fopen( fileName.c_str(), mode );
  if ( !hFile )
  {
    DebugTrace( "Failed to open file %s", fileName.c_str() );
    SetBroken( true );
    return;
  }
  
  SetCanRead( false );
  SetCanWrite( true );
  SetCanSeek( false );
  SetBroken( false );
}
