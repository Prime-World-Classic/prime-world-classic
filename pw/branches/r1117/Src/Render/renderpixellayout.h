#pragma once
//////////////////////////////////////////////////////////////////////////
// Порядок байтов 32-битного пикселя при чтении поверхности бэкендом.
//
// Вынесено из IRenderBackend намеренно: это формат данных, а не часть
// интерфейса. Читателям пикселей (Render/screenshot.{h,cpp}) нужен только он,
// без D3D9, Windows-типов и stdafx клиента — благодаря этому писатель снимков
// компилируется и проверяется отдельно от графа клиента (tools/screenshot_test).

namespace Render
{
  // D3D9-поверхность A8R8G8B8/X8R8G8B8 лежит в памяти как B,G,R,A; у
  // Vulkan-бэкенда этапа 3 естественный ответ — R,G,B,A. Разницу не прячем:
  // пишущий код сам переставляет каналы, иначе на этапе 3 картинка молча
  // поменяет каналы местами (за это и отвечает явный параметр в ReadSurface).
  enum EBackendPixelLayout {
    plBGRA = 0,
    plRGBA = 1,
  };
}
